merge_skill_csvs() {
  local merged="" csv item
  for csv in "$@"; do
    [ -n "$csv" ] || continue
    [ "$csv" = "none" ] && continue
    IFS=',' read -r -a items <<< "$csv"
    for item in "${items[@]}"; do
      item="$(printf '%s' "$item" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
      [ -n "$item" ] || continue
      skill_exists "$item" || continue
      merged="$(append_unique_csv "$merged" "$item")"
    done
  done
  printf '%s\n' "${merged:-none}"
}

csv_to_multiline() {
  local csv="$1" item
  [ "$csv" = "none" ] && return 0
  IFS=',' read -r -a items <<< "$csv"
  for item in "${items[@]}"; do
    item="$(printf '%s' "$item" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
    [ -n "$item" ] || continue
    printf '%s\n' "$item"
  done
}

