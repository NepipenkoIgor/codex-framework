choose_tier_from_role_and_task() {
  local role="$1"
  local task_lc="$2"
  local shape="$3"
  local contract_task="no"
  local tier="medium"
  if task_contains "$task_lc" 'new api|schema|contract|migration|dependency|cross-system|cross system|parallel'; then
    contract_task="yes"
  fi
  [ "$shape" = "mechanical" ] && [ "$contract_task" = "no" ] && tier="low"
  case "$role" in
    estimator)
      tier="medium"
      ;;
    framework-manager)
      if task_contains "$task_lc" 'framework gap|framework status|status.*framework|framework orchestration|orchestration audit|agent quality|human-like|human like|senior engineer agent|production readiness|operating model|orchestration redesign|skill architecture|runtime guard|codex hook|codex hooks|hook-native|runtime hook|lifecycle automation|хуки|хук|выжимать.*codex|prompt coding|промпт[ -]?кодинг|статус.*фреймвор|оркестрац|агент|агентов|доменные знания|валидац.*фреймворк'; then
        tier="xhigh"
      else
        tier="high"
      fi
      ;;
    architect|builder-fullstack|builder-ai|builder-n8n|builder-automation|refactorer)
      tier="high"
      ;;
    project-manager)
      if task_contains "$task_lc" 'create pr|open pr|publish pr|pr body|release summary|commit|stage changes|git status|push branch|создай pr|создать pr|открой pr|пулл реквест|коммит'; then
        tier="low"
      else
        tier="medium"
      fi
      ;;
    fixer)
      tier="medium"
      task_contains "$task_lc" 'across|cross-system|cross system|multi-system|multi service|migration|webhook|concurrency|deadlock|race condition|distributed' && tier="high"
      [ "$shape" = "mechanical" ] && [ "$contract_task" = "no" ] && tier="low"
      ;;
    reviewer|tester|builder-frontend|builder-backend|builder-infra|builder-mobile|builder|auditor)
      [ "$tier" = "low" ] || tier="medium"
      ;;
  esac
  if [ "$contract_task" = "yes" ] && [ "$tier" != "xhigh" ] && [ "$role" != "estimator" ]; then
    tier="high"
  fi
  printf '%s\n' "$tier"
}

infer_domains_for_task() {
