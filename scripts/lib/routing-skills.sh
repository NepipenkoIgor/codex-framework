repo_intelligence_stale() {
  local file="$1"
  local expected actual
  [ -f "$file" ] || return 0
  expected="$(repo_intelligence_fingerprint)"
  actual="$(sed -n 's/^RI_FINGERPRINT=//p' "$file" | tail -n 1)"
  actual="${actual#\'}"
  actual="${actual%\'}"
  [ -n "$actual" ] || return 0
  [ "$expected" != "$actual" ]
}

