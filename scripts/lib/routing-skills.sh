append_unique_csv() {
  local csv="$1"
  local value="$2"
  local item
  [ -n "$value" ] || {
    printf '%s\n' "$csv"
    return 0
  }
  IFS=',' read -r -a existing_items <<< "$csv"
  for item in "${existing_items[@]-}"; do
    item="$(printf '%s' "$item" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
    [ "$item" = "$value" ] && {
      printf '%s\n' "$csv"
      return 0
    }
  done
  if [ -z "$csv" ]; then
    printf '%s\n' "$value"
  else
    printf '%s,%s\n' "$csv" "$value"
  fi
}

